// Generates src/styles/utilities.css from the spacing scale in tokens.css.
// Run: node packages/game-kit/scripts/generate-utilities.ts
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const stylesDir = new URL('../src/styles/', import.meta.url)

const sides = {
  '': ['{p}'],
  t: ['{p}-top'],
  r: ['{p}-right'],
  b: ['{p}-bottom'],
  l: ['{p}-left'],
  x: ['{p}-left', '{p}-right'],
  y: ['{p}-top', '{p}-bottom'],
} as const

export function readSpacingSizes(tokensCss: string): string[] {
  return [...tokensCss.matchAll(/--spacing-([a-z]+):/g)].map((m) => m[1] as string)
}

export function buildUtilities(sizes: string[]): string {
  const rules: string[] = []
  for (const [abbr, prefix] of [
    ['m', 'margin'],
    ['p', 'padding'],
  ] as const) {
    for (const [side, props] of Object.entries(sides)) {
      for (const size of sizes) {
        const decls = props
          .map((p) => `${p.replace('{p}', prefix)}: var(--spacing-${size});`)
          .join(' ')
        rules.push(`  .${abbr}${side}-${size} { ${decls} }`)
      }
    }
  }
  for (const size of sizes) rules.push(`  .gap-${size} { gap: var(--spacing-${size}); }`)
  rules.push('  .text-center { text-align: center; }')
  rules.push(
    '  .visually-hidden { position: absolute; width: 1px; height: 1px; padding: 0; margin: -1px; overflow: hidden; clip-path: inset(50%); white-space: nowrap; border: 0; }',
  )
  return `/* Generated by packages/game-kit/scripts/generate-utilities.ts, do not edit. */\n@layer utilities {\n${rules.join('\n')}\n}\n`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const tokens = readFileSync(new URL('tokens.css', stylesDir), 'utf8')
  writeFileSync(new URL('utilities.css', stylesDir), buildUtilities(readSpacingSizes(tokens)))
}
